const COLOUR_TO_CHANGE = RED;  // Change for each script
const ACTION = true; // True is add

const UNIVERSE = 0; // 0-indexed
const FIXTURE_1 = 0;
const FIXTURE_2 = 1;
const CHANNEL = 1;  // 0-indexed

function lookupColour (dmx)
{
    for (i = 0; i < DMX_LOOKUP.length; i++)
    {
        if (DMX_LOOKUP[i] === dmx)
        {
            return i;
        }
    }
}

function doShift ()
{
    const current = Engine.getChannelValue (UNIVERSE, CHANNEL);
    colour = lookupColour (current);

    if (ACTION)
    {
        colour |= COLOUR_TO_CHANGE;
    }
    else
    {
        colour &= ~COLOUR_TO_CHANGE;
    }
    Engine.setFixture (FIXTURE_1, CHANNEL, DMX_LOOKUP[colour]);
    Engine.setFixture (FIXTURE_2, CHANNEL, DMX_LOOKUP[colour]);
}

doShift();
